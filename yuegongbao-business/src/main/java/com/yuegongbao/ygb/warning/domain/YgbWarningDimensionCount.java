package com.yuegongbao.ygb.warning.domain;

public class YgbWarningDimensionCount
{
    private String dimensionKey;

    private String dimensionLabel;

    private Integer dimensionCount;

    public String getDimensionKey()
    {
        return dimensionKey;
    }

    public void setDimensionKey(String dimensionKey)
    {
        this.dimensionKey = dimensionKey;
    }

    public String getDimensionLabel()
    {
        return dimensionLabel;
    }

    public void setDimensionLabel(String dimensionLabel)
    {
        this.dimensionLabel = dimensionLabel;
    }

    public Integer getDimensionCount()
    {
        return dimensionCount;
    }

    public void setDimensionCount(Integer dimensionCount)
    {
        this.dimensionCount = dimensionCount;
    }
}
